        <div>
          <h2>Method</h2>
          <ol class="method"><li><p>Put everything for the sauce except the water in a jar and shake, or whisk it in a bowl. It will seize into a stiff paste. That is expected.</p></li><li><p>Add the warm water a tablespoon at a time, mixing after each, until it pours slowly off a spoon. Adding it all at once makes a split, grainy sauce that will not come back.</p></li><li><p>Cook the noodles as the packet says, then rinse under cold water until completely cool. Rinsing removes the surface starch that would otherwise glue them together in the fridge.</p></li><li><p>Toss the noodles with about half the sauce, enough to coat every strand.</p></li><li><p>Pile into bowls with the carrot, cucumber, edamame and spring onion arranged in sections rather than mixed through, then spoon more sauce over the top.</p></li><li><p>Finish with sesame seeds and coriander. Keep the rest of the sauce in the jar in the fridge.</p></li></ol>
