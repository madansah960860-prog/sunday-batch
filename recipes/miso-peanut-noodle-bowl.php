            <div>
              <h3>Batch on Sunday</h3>
              <p>Make a double jar of the sauce on Sunday. It is the entire recipe and it takes four minutes. Cook and rinse the noodles too; cut the carrot and cucumber on the day, because they go limp.</p>
            </div>
            <div>
              <h3>How it keeps</h3>
              <p>Sauce: two weeks refrigerated, and it thickens as it sits &mdash; loosen with a little warm water. Dressed noodles: two days. Undressed cooked noodles: four days.</p>
            </div>
            <div>
              <h3>What to swap</h3>
              <ul><li>Any nut or seed butter. Tahini works and is cheaper.</li><li>Any raw crunchy vegetable: cabbage, pepper, mangetout, radish, fennel.</li><li>Add crisp tofu, or a jammy egg if you are not vegan.</li><li>The same sauce dresses a slaw, a grain bowl or roast broccoli.</li></ul>
