              <h3>Batch on Sunday</h3>
              <p>Make the green base on Sunday without the eggs. It is the whole dish minus six minutes. Reheat a portion in a small pan and crack an egg into it on the day.</p>
            </div>
            <div>
              <h3>How it keeps</h3>
              <p>The base keeps four days refrigerated and freezes for three months. Never store it with eggs in &mdash; cooked egg reheated in a sauce goes rubbery.</p>
            </div>
            <div>
              <h3>What to swap</h3>
              <ul><li>Any dark leaf: chard, kale, cavolo nero, even watercress.</li><li>Any white bean, or chickpeas.</li><li>Crumbled feta instead of eggs if you eat dairy.</li><li>Serve on toast, on rice, or with flatbread.</li></ul>
