          <h2>Method</h2>
          <ol class="method"><li><p>Heat the oil in a wide pan and cook the leek gently for 6 minutes until soft but not coloured.</p></li><li><p>Add the garlic, chilli, cumin and coriander and cook 1 minute.</p></li><li><p>Add the spinach in handfuls, letting each wilt before the next. It looks like far too much and collapses to about a fifth.</p></li><li><p>Add the beans, stock and salt. Simmer 3 minutes.</p></li><li><p>Stir in three-quarters of the herbs and take the pan off the heat for a moment. Blitz about a third of the mixture with a stick blender, or mash it against the side, so the sauce holds together.</p></li><li><p>Make four wells. Crack in the eggs, season them, cover the pan and cook on a low heat for 6&ndash;8 minutes until the whites are set and the yolks are still soft. For a vegan version, crumble in firm tofu at step four and skip the wells.</p></li><li><p>Finish with the rest of the herbs and a hard squeeze of lemon. The acid is what stops it tasting flat and green.</p></li></ol>
