          <h2>Method</h2>
          <ol class="method"><li><p>Heat the oven to 200&deg;C fan / 220&deg;C conventional / 425&deg;F.</p></li><li><p>Dry the chickpeas thoroughly on a tea towel, then roll them gently to slip off any loose skins. Both steps matter: wet chickpeas steam, and the loose skins burn before the chickpea crisps.</p></li><li><p>Toss with the oil, paprika, cumin and salt. Spread on a large tray with the tomatoes and onion, in one layer.</p></li><li><p>Roast 30&ndash;35 minutes, shaking once. The chickpeas should be firm and nutty, not soft.</p></li><li><p>Meanwhile cook the grains in well-salted water until tender, drain, and leave uncovered to steam dry for five minutes.</p></li><li><p>Whisk the tahini with the lemon, garlic and salt. It will seize. Add the cold water a spoonful at a time until it is smooth and pourable &mdash; cold water, not warm, and slowly.</p></li><li><p>Fold the spinach through the hot grains so it wilts, then top with the tray contents, the dressing and a squeeze of lemon.</p></li></ol>
