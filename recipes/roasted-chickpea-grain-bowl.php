            <div>
              <h3>Batch on Sunday</h3>
              <p>Roast a double tray of chickpeas and cook a full pan of grains on Sunday. Make the dressing in a jar. Assemble each morning in about ninety seconds.</p>
            </div>
            <div>
              <h3>How it keeps</h3>
              <p>Grains four days. Roasted chickpeas three days, and they soften &mdash; five minutes in a hot oven brings them back. Tahini dressing five days; it thickens, so loosen with water.</p>
            </div>
            <div>
              <h3>What to swap</h3>
              <ul><li>Any grain: quinoa, freekeh, bulgur, or leftover rice.</li><li>Butter beans instead of chickpeas, roasted the same way.</li><li>Any roasting vegetable: squash, broccoli, cauliflower, peppers.</li><li>Swap tahini for the miso peanut sauce from the noodle bowl.</li></ul>
