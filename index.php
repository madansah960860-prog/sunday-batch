      <div class="prose">
        <h2>Ninety minutes on a Sunday</h2>
        <p>The six recipes here are designed to overlap. The miso peanut sauce
          dresses the noodles and the slaw. The tahini dressing from the grain
          bowl works on everything. The roasted chickpeas go in the grain bowl,
          on the slaw, or straight into a lunchbox.</p>
        <p>Cook the lentil stew and the grains at the same time, roast the
          chickpeas while they simmer, make two jars of dressing and five jars
          of oats while the oven is on, and salt the cabbage for the slaw
          first thing so it drains while everything else happens. That is
          about ninety minutes and it is most of a week of lunches.</p>
        <p>None of that is a rule. If you only have forty minutes, make the
          stew and the oats and skip the rest; that is still four dinners and
          five breakfasts. The plan is a shape to borrow from rather than a
          programme to follow, and nobody here is going to be disappointed in
          you on Wednesday.</p>
        <p>The one step worth doing first every time is salting the cabbage,
          because it needs half an hour of standing and nothing else does. Put
          it in a colander before you do anything else and it will be ready
          when you are.</p>
