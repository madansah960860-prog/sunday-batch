          <h2>What actually keeps, honestly</h2>
          <p>Meal-prep writing is full of cheerful claims about five days. Most
            of them are wrong, and the difference between a component that
            keeps and one that does not is usually water.</p>
          <p><strong>Keeps four to five days:</strong> cooked grains, roasted
            chickpeas (they soften but revive in a hot oven), the lentil stew,
            overnight oats, and the salted slaw &mdash; which genuinely
            improves for three days because the salting removed the water that
            would otherwise have made it soggy.</p>
          <p><strong>Keeps two days at best:</strong> anything dressed with oil
            and acid that has not been salted first, cut cucumber, avocado,
            soft herbs, and cooked noodles that were not rinsed cold.</p>
          <p><strong>Does not keep at all:</strong> eggs cooked into a sauce,
            anything crisp, and toasted nuts or seeds left in a wet mixture.
            Keep those in a separate pot and add them at the last second.</p>

          <h2>The three things that make prep work</h2>
          <p><strong>Salt vegetables that release water.</strong> Cabbage,
            cucumber, courgette. Thirty minutes of salting and a hard squeeze
            is the difference between a slaw that lasts four days and one that
            is soup on Tuesday.</p>
          <p><strong>Rinse cooked noodles and grains cold.</strong> It washes
            off the surface starch that glues them together in the fridge.</p>
          <p><strong>Store components, not meals.</strong> A box of dressed
            assembled salad degrades to the speed of its wettest ingredient. The
            same food in three pots keeps for days and takes ninety seconds to
            put together.</p>
        </div>
        <div class="prose">
          <h2>Containers, briefly</h2>
          <p>Glass, because it does not stain, does not hold smells and goes in
            the oven. Straight-sided jars for oats and dressings. Nothing here
            requires a matching set and none of it needs to be bought new.</p>
          <p>The single most useful item is a set of small pots for the things
            that must stay dry: sesame seeds, toasted nuts, crisp chickpeas,
            chopped herbs.</p>

          <h2>Freezing</h2>
          <p>Only one of these six freezes genuinely well, and it is the lentil
            stew. Freeze it in single portions rather than one large block,
            because a Tuesday is not improved by defrosting two litres of
            stew.</p>
          <p>Overnight oats freeze acceptably for a month. The noodle bowl, the
            slaw and the grain bowl do not freeze at all &mdash; the textures
            that make them worth eating are exactly the ones that ice crystals
            destroy.</p>

          <h2>Food safety, which matters more when you cook ahead</h2>
          <p>Cool cooked food quickly and get it into the fridge within two
            hours, one in hot weather. Keep the fridge at or below 5&deg;C.
            Reheat once only, until piping hot throughout &mdash; 74&deg;C /
            165&deg;F. Full detail is on the
            <a href="../policies/disclaimer.php">disclaimer page</a> and it is
            worth reading if you are batch cooking every week.</p>
        </div>
