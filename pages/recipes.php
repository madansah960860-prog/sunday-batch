          <h2>How these six fit together</h2>
          <p>They share components on purpose. Two recipes use the miso peanut
            sauce. Two use a tahini dressing that takes ninety seconds. The
            roasted chickpeas belong in three of them. Nothing here is a
            one-off that leaves you with half a jar of something you will never
            use again.</p>
          <p>That is the practical difference between recipes written for a
            single dinner and recipes written for a week, and it is why the
            substitution list on each page is as long as it is.</p>
          <h2>What is coming</h2>
          <p>A crispy tofu bowl that is currently too fiddly, a proper
            white-bean and rosemary soup, a set of three dressings in one post,
            and a savoury breakfast that is not eggs. None will go up without a
            meal-prep note that has actually been tested for four days in a
            real fridge.</p>
        </div>
        <div class="prose">
          <h2>Reading a recipe here</h2>
          <p>The meal-prep tile sits above the ingredients rather than at the
            bottom, which is deliberate. On most recipe sites the storage note
            is the last thing on the page, under the comments, and for the way
            people actually cook it is one of the first things worth knowing.</p>
          <p>Nutrition is a plain two-column list, clearly marked as an
            estimate, and it is the least decorated thing on the page. That is
            also deliberate: these are calculated figures, not measurements,
            and dressing them up as a designed infographic would imply a
            precision they do not have.</p>
        </div>
