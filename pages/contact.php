          <p>Fridge temperature is the variable nobody checks. A fridge at
            8&deg;C rather than 5&deg;C will cut a four-day keeping time to
            about two, and a great many domestic fridges sit at 8&deg;C. A
            fridge thermometer costs about four pounds and is the cheapest
            improvement to a meal-prep routine available.</p>

          <h2>Fridge temperature, the thing nobody checks</h2>
          <p>Every keeping time on this site assumes a fridge at or below
            5&deg;C. A great many domestic fridges sit at 7 or 8&deg;C, usually
            because the dial has never been touched or because the back is
            packed solid and the air cannot move.</p>
          <p>At 8&deg;C a four-day component is a two-day component. If several
            things here have gone off earlier than we said, that is the first
            thing to check, and a fridge thermometer costs about four pounds.</p>

          <h2>Substitutions</h2>
          <p>Every recipe has a substitution list because the point is to use
            what you have. If the thing you want to swap is not on the list,
            ask &mdash; the answer is usually yes, and where it is no there is
            normally a specific structural reason, like the salting step in the
            slaw or the cold-rinsing of the noodles.</p>

          <h2>What we cannot help with</h2>
          <p>Medical diets, exact nutrition for your version, or whether a
            recipe is safe for a particular allergy. Our figures are estimates
            and our allergen notes cover the recipe as written; the reasons are
            in the <a href="../policies/disclaimer.php">disclaimer</a>, and
            they are worth reading properly if you cook for someone with an
            allergy.</p>
          <p>We do not accept guest posts, sponsored recipes or link requests,
            and those emails are deleted without a reply.</p>

          <h2>Requests</h2>
          <p>Welcome, and the most useful version names the constraint rather
