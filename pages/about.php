          <h2>Who writes it</h2>
          <p>Robin Oyelaran cooked in two vegetarian restaurants in Bristol for
            six years, then spent three more as a food development assistant
            working on chilled ready meals, which is an education in exactly
            one thing: what happens to food after four days in a fridge.</p>
          <p>That is the entire premise of this site. Almost every recipe site
            tells you how to cook something once. Very few tell you what it is
            like on Wednesday, and for most people cooking on a weeknight that
            is the more useful information.</p>

          <h2>Why every recipe has a meal-prep note</h2>
          <p>Because the question is rarely &ldquo;how do I make this&rdquo;.
            It is &ldquo;what can I make on Sunday that I will still want to
            eat on Thursday&rdquo;, and answering it requires knowing which
            components hold, which go watery, and what to add at the last
            minute.</p>
          <p>The notes are tested the boring way: the thing is made, portioned,
            refrigerated and eaten on each of the following four days, and what
            is written down is what actually happened. Two recipes have had
            their keeping times reduced after that test.</p>

          <h2>How the recipes are tested</h2>
          <p>Each is cooked at least four times, once by a second cook working
            only from the written text, and then put through the four-day
            fridge test. Quantities are recorded in grams while cooking and the
            cup measures are converted from those weights afterwards.</p>
        </div>
        <div class="prose">
          <h2>What this site will not say</h2>
          <p>That plant-based food is clean, detoxifying, anti-inflammatory,
            alkalising, or that it will fix anything about you. It is food. A
            lot of it contains a great deal of peanut butter and coconut milk,
            and the nutrition figures on every page are clearly labelled as
            estimates.</p>
          <p>There is also no weight-loss framing anywhere on this site, no
            calorie-first presentation, and no language about foods being good
            or bad. If you want a recipe site that ranks lunches by calorie
            count, this is deliberately not it.</p>

          <h2>On being plant-based without being preachy</h2>
          <p>Everything here is vegetarian and most of it is vegan. Nobody will
            be lectured about it. Two recipes use eggs or dairy and give a vegan
            version in the ingredient list rather than in a footnote, and if you
            want to put feta on the shakshuka that is a good idea and we will
            not mention it again.</p>

          <h2>The four-day fridge test</h2>
          <p>Every recipe is portioned into containers on the day it is cooked
            and then eaten on each of the following four days, with a note
            written each time. It is a dull test and it is the only way to know
            whether a keeping claim is true.</p>
          <p>Two recipes failed it and were changed. The slaw was published at
            five days and is now four, after the test was repeated in July in a
            warmer kitchen. The noodle bowl needed a step added &mdash; rinsing
            the noodles cold &mdash; because without it day two was a solid
            block.</p>

          <h2>Money</h2>
          <p>Display advertising only. No affiliate links, no sponsored posts,
            no brand partnerships and nothing for sale. Three plant-milk brands
            and a meal-kit company have asked; all four were declined. The
            detail is on the
            <a href="../policies/advertising-disclosure.php">advertising
            disclosure</a> page.</p>

          <h2>Corrections</h2>
          <p>Two. The slaw originally claimed five days and is now four, after
            the fridge test was repeated in summer. And the noodle bowl did not
            originally say to rinse the noodles cold, which is the one step
            that makes it survive to day two at all.</p>
